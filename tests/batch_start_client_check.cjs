const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../web/launcher/app.js'), 'utf8').split('const $ =')[0];
const context = vm.createContext({});
vm.runInContext(source + '\nglobalThis.startControl=batchStartControl;', context);
const control = context.startControl;
const idle = {running:false, error:null, batch:{status:'complete'}, jobs:[], presets:[{name:'测试预设'}]};
assert.equal(control(idle, false).disabled, false);
const organizing = {...idle, running:true, storage:{maintenance:{status:'running'}}};
assert.match(control(organizing, false).hint, /运行锁/);
assert.equal(control({...idle, storage:{maintenance:{status:'complete'}}}, false).disabled, false);
assert.equal(control({...idle, running:true}, false).disabled, true);
assert.match(control({...idle, running:true}, false).hint, /运行锁/);
assert.equal(control({...idle, batch:{status:'paused'}}, false).disabled, true);
assert.equal(control({...idle, error:'数据库不可用'}, false).hint, '数据库不可用');
assert.equal(control(idle, true).disabled, true);
assert.match(control({...idle, jobs:[{status:'running',resources:['mail'],title:'邮箱检查'}]}, false).hint, /邮箱检查/);
assert.equal(control({...idle, presets:[]}, false).disabled, true);
assert.match(control({...idle, preset_error:'云端不可达'}, false).hint, /云端不可达/);
console.log('Batch start controls passed');
